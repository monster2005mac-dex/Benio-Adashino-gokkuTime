export const formatDateKey = (d) => {
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
};

export const getWeekDays = (selectedDateStr) => {
  const d = new Date(selectedDateStr + 'T12:00:00');
  const dayIdx = d.getDay();
  const diffToMonday = dayIdx === 0 ? -6 : 1 - dayIdx;

  const monday = new Date(d);
  monday.setDate(d.getDate() + diffToMonday);

  const days = [];
  const dayNames = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];
  const dayShorts = ['Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat', 'Sun'];

  for (let i = 0; i < 7; i++) {
    const cur = new Date(monday);
    cur.setDate(monday.getDate() + i);
    days.push({
      dateKey: formatDateKey(cur),
      dayName: dayNames[i],
      dayShort: dayShorts[i],
      dayNumber: cur.getDate(),
      monthShort: cur.toLocaleDateString('en-US', { month: 'short' }),
      displayHeader: `${dayShorts[i]}, ${cur.toLocaleDateString('en-US', { month: 'short', day: 'numeric' })}`
    });
  }
  return days;
};

